// assetRef turns an asset id into the asset reference attached on a finding (label follows the same precedence as backend coverageNodeLabel
// the precedence is the same as backend coverageNodeLabel (URL > domain > IP > app name). The "by asset" tree view is built on these references
// .
function assetRef(id: number): FindingAsset {
  const asset = assets.find((candidate) => candidate.id === id);
  if (!asset) throw new Error(`mock assetRef: unknown asset ${id}`);
  return {
    id: String(id),
    type: asset.type,
    label: asset.url || asset.domain || asset.ip || asset.app_name || String(id),
  };
}

